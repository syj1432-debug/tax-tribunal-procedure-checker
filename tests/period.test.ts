// 청구기간 경과 점검 시험
// Design Ref: §3-2 — Vitest로 기간 계산이 맞는지 자동으로 확인한다.
// Plan SC: "청구기간 계산이 민법 기준으로 맞고, 우편소인일 규칙이 시험 사례에서 맞게 나온다" (PLAN 성공 기준)
//
// 실행: npm test

import { describe, expect, it } from "vitest";

import 시험 from "../samples/시험사례.json";
import { 올바른날짜, 요일번호, 일수더하기 } from "../lib/rules/dates";
import { 휴일인지 } from "../lib/rules/holidays";
import { 청구기간점검 } from "../lib/rules/period";
import type { 사건정보 } from "../lib/types";

const 사건 = (값: Partial<사건정보>): 사건정보 => ({ 모드: "실제", ...값 });

describe("날짜 계산", () => {
  it("90일을 더한다 (초일 불산입 기준 말일)", () => {
    expect(일수더하기("2026-03-10", 90)).toBe("2026-06-08");
  });
  it("월말을 넘겨도 맞다", () => {
    expect(일수더하기("2026-01-31", 1)).toBe("2026-02-01");
    expect(일수더하기("2026-12-31", 1)).toBe("2027-01-01");
  });
  it("없는 날짜는 올바르지 않다고 본다", () => {
    expect(올바른날짜("2026-02-30")).toBe(false);
    expect(올바른날짜("2026-6-8")).toBe(false);
    expect(올바른날짜("2026-06-08")).toBe(true);
  });
  it("요일을 구한다", () => {
    expect(요일번호("2026-06-08")).toBe(1); // 월요일
  });
});

describe("휴일 판정", () => {
  it("토·일요일은 연도와 상관없이 휴일이다", () => {
    expect(휴일인지("2027-04-03").결과).toBe("휴일"); // 토요일
    expect(휴일인지("2027-04-04").결과).toBe("휴일"); // 일요일
  });
  it("2026년 공휴일·대체공휴일을 안다", () => {
    for (const 날 of ["2026-03-02", "2026-05-01", "2026-05-25", "2026-06-03", "2026-08-17", "2026-10-05"]) {
      expect(휴일인지(날).결과).toBe("휴일");
    }
  });
  it("2026년 평일은 평일이다", () => {
    expect(휴일인지("2026-06-08").결과).toBe("평일");
  });
  it("목록에 없는 연도의 평일은 알 수 없다고 한다", () => {
    expect(휴일인지("2027-04-05").결과).toBe("알수없음");
  });
});

describe("샘플 시험 사례 (samples/시험사례.json)", () => {
  for (const 사례 of 시험.사례) {
    it(`${사례.id}: 청구기간 ${사례.기대.청구기간}`, () => {
      const 결과 = 청구기간점검({ 모드: "가상", ...사례.입력 } as 사건정보);
      expect(결과.상태).toBe(사례.기대.청구기간);
      expect(결과.상태뜻.length).toBeGreaterThan(0);
      if ("추정" in 사례 && 사례.추정) {
        expect(결과.계산과정).toContain("추정");
      }
    });
  }

  it("우편소인일 규칙 사례(03)는 청구일로 보는 날을 기한일(6/8)로 보여준다", () => {
    const 사례 = 시험.사례.find((c) => c.id === "03-우편소인일규칙")!;
    const 결과 = 청구기간점검({ 모드: "가상", ...사례.입력 } as 사건정보);
    expect(결과.계산과정).toContain("청구일로 보는 날: 2026-06-08(월)");
  });

  it("청구기간 경과 사례(02)는 미충족이고 조문 확인 필요 안내가 켜진다", () => {
    const 사례 = 시험.사례.find((c) => c.id === "02-청구기간경과")!;
    const 결과 = 청구기간점검({ 모드: "가상", ...사례.입력 } as 사건정보);
    expect(결과.상태).toBe("미충족");
    expect(결과.조문확인필요).toBe(true);
  });
});

describe("기한 경계와 말일 특례", () => {
  // 처분을 안 날 2026-03-10 → 말일 2026-06-08(월, 평일)
  const 기본 = { 처분을안날: "2026-03-10" };

  it("말일 당일 접수는 충족이다", () => {
    expect(청구기간점검(사건({ ...기본, 접수일: "2026-06-08" })).상태).toBe("충족");
  });
  it("말일 다음 날 접수(우편소인일 없음)는 확인 필요다", () => {
    expect(청구기간점검(사건({ ...기본, 접수일: "2026-06-09" })).상태).toBe("확인 필요");
  });
  it("말일 다음 날 접수여도 우편소인일이 같은 날 이후면 미충족이다", () => {
    expect(청구기간점검(사건({ ...기본, 접수일: "2026-06-09", 우편소인일: "2026-06-09" })).상태).toBe("미충족");
  });
  it("접수일이 없어도 우편소인일이 말일 이내면 충족이다", () => {
    expect(청구기간점검(사건({ ...기본, 우편소인일: "2026-06-08" })).상태).toBe("충족");
  });

  it("말일이 토요일이면 월요일까지 미룬다 (말일 6/6 토 → 기한 6/8 월)", () => {
    const 값 = { 처분을안날: "2026-03-08" };
    const 당일 = 청구기간점검(사건({ ...값, 접수일: "2026-06-08" }));
    expect(당일.상태).toBe("충족");
    expect(당일.계산과정).toContain("기한: 2026-06-08(월)");
    expect(청구기간점검(사건({ ...값, 접수일: "2026-06-09", 우편소인일: "2026-06-09" })).상태).toBe("미충족");
  });
  it("말일이 공휴일이면 다음 날로 미룬다 (말일 5/5 어린이날 → 기한 5/6)", () => {
    const 값 = { 처분을안날: "2026-02-04" };
    expect(청구기간점검(사건({ ...값, 접수일: "2026-05-06" })).상태).toBe("충족");
    expect(청구기간점검(사건({ ...값, 접수일: "2026-05-07", 우편소인일: "2026-05-07" })).상태).toBe("미충족");
  });
  it("연휴가 이어지면 연휴가 끝날 때까지 미룬다 (말일 9/25 추석 → 기한 9/28 월)", () => {
    const 값 = { 처분을안날: "2026-06-27" };
    const 결과 = 청구기간점검(사건({ ...값, 접수일: "2026-09-28" }));
    expect(결과.상태).toBe("충족");
    expect(결과.계산과정).toContain("기한: 2026-09-28(월)");
    expect(청구기간점검(사건({ ...값, 접수일: "2026-09-29", 우편소인일: "2026-09-29" })).상태).toBe("미충족");
  });
});

describe("없는 값과 목록에 없는 연도", () => {
  it("처분을 안 날과 처분일이 모두 없으면 확인 필요다", () => {
    expect(청구기간점검(사건({ 접수일: "2026-04-06" })).상태).toBe("확인 필요");
  });
  it("접수일과 우편소인일이 모두 없으면 확인 필요다", () => {
    expect(청구기간점검(사건({ 처분을안날: "2026-03-10" })).상태).toBe("확인 필요");
  });
  it("처분을 안 날이 없고 처분일만 있으면 처분일로 계산하고 추정을 표시한다", () => {
    const 결과 = 청구기간점검(사건({ 처분일: "2026-03-10", 접수일: "2026-04-06" }));
    expect(결과.상태).toBe("충족");
    expect(결과.계산과정).toContain("추정");
    expect(결과.근거).toContain("추정");
  });
  it("처분을 안 날이 있으면 처분일은 쓰지 않는다", () => {
    // 처분일(3/1) 기준이면 6/6(토)→6/8, 안 날(3/10) 기준이면 6/8. 안 날 기준으로 계산해야 한다.
    const 결과 = 청구기간점검(사건({ 처분일: "2026-03-01", 처분을안날: "2026-03-10", 접수일: "2026-06-08" }));
    expect(결과.계산과정).toContain("처분을 안 날: 2026-03-10(화)");
    expect(결과.계산과정).not.toContain("추정");
  });
  it("2027년처럼 공휴일 목록이 없는 연도에서 말일을 넘기면 확인 필요다", () => {
    // 안 날 2027-01-05 → 말일 2027-04-05(월). 접수일이 하루 늦다.
    const 결과 = 청구기간점검(사건({ 처분을안날: "2027-01-05", 접수일: "2027-04-06", 우편소인일: "2027-04-06" }));
    expect(결과.상태).toBe("확인 필요");
    expect(결과.계산과정).toContain("공휴일 목록에 해당 연도를 추가");
  });
  it("2027년이어도 접수일이 말일 이내면 공휴일 목록 없이 충족이다", () => {
    expect(청구기간점검(사건({ 처분을안날: "2027-01-05", 접수일: "2027-04-05" })).상태).toBe("충족");
  });
  it("날짜 형식이 잘못되면 확인 필요다", () => {
    const 결과 = 청구기간점검(사건({ 처분을안날: "2026-3-10", 접수일: "2026-04-06" }));
    expect(결과.상태).toBe("확인 필요");
    expect(결과.근거).toContain("형식");
  });
});
