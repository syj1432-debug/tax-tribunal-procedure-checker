// 대리인 부적격 점검 시험
// Design Ref: §3-2 — Vitest로 규칙이 맞는지 자동으로 확인한다.
// Plan SC: 네 가지 점검이 모두 충족 / 미충족 / 확인 필요 / 판단 필요 중 하나로 나온다 (PLAN 성공 기준)
//
// 실행: npm test

import { describe, expect, it } from "vitest";

import 시험 from "../samples/시험사례.json";
import { 대리인부적격점검 } from "../lib/rules/agent";
import type { 사건정보 } from "../lib/types";

const 사건 = (값: Partial<사건정보>): 사건정보 => ({ 모드: "실제", ...값 });
const 대리 = (관계자격: string, 나머지: Partial<사건정보> = {}) =>
  대리인부적격점검(사건({ 대리인: "박샘플", 대리인관계자격: 관계자격, 사건유형: "소액", 청구금액: 3_000_000, ...나머지 }));

describe("샘플 시험 사례 (samples/시험사례.json)", () => {
  for (const 사례 of 시험.사례) {
    it(`${사례.id}: 대리인 부적격 ${사례.기대.대리인부적격}`, () => {
      const 결과 = 대리인부적격점검({ 모드: "가상", ...사례.입력 } as 사건정보);
      expect(결과.항목).toBe("대리인부적격");
      expect(결과.상태).toBe(사례.기대.대리인부적격);
      expect(결과.상태뜻.length).toBeGreaterThan(0);
      expect(결과.근거).toContain("국세기본법 제59조"); // 대조한 기준을 보여준다
    });
  }
});

describe("대리인이 없을 때", () => {
  it("대리인이 없으면 충족(해당 없음)이다", () => {
    expect(대리인부적격점검(사건({})).상태).toBe("충족");
    expect(대리인부적격점검(사건({ 대리인: "  " })).상태).toBe("충족");
  });
});

describe("확인 필요", () => {
  it("대리인은 있는데 관계·자격이 없다", () => {
    expect(대리인부적격점검(사건({ 대리인: "박샘플" })).상태).toBe("확인 필요");
  });
  it("가족 대리인데 사건 유형이 없다", () => {
    expect(대리("청구인의 배우자", { 사건유형: null }).상태).toBe("확인 필요");
  });
  it("소액 사건인데 청구금액이 없다", () => {
    expect(대리("청구인의 배우자", { 청구금액: null }).상태).toBe("확인 필요");
  });
});

describe("전문직 대리인 (제59조 제1항) — 사건 유형과 상관없이 가능", () => {
  it("변호사는 일반 사건에서도 충족이다", () => {
    expect(대리("변호사", { 사건유형: "일반", 청구금액: 90_000_000 }).상태).toBe("충족");
  });
  it("세무사는 충족이다", () => {
    expect(대리("세무사 (등록)", { 사건유형: "일반" }).상태).toBe("충족");
  });
  it("공인회계사는 등록 여부가 없으면 판단 필요, 등록이 적혀 있으면 충족이다", () => {
    expect(대리("공인회계사").상태).toBe("판단 필요");
    expect(대리("공인회계사 (세무대리업무등록)").상태).toBe("충족");
  });
  it("자격 없음이라고 적힌 글은 자격이 있다고 읽지 않는다", () => {
    expect(대리("세무사 자격 없음").상태).not.toBe("충족");
  });
});

describe("가족 대리인 (제59조 제2항) — 소액 사건에서만", () => {
  it("소액 사건의 배우자는 충족이다", () => {
    expect(대리("청구인의 배우자").상태).toBe("충족");
  });
  it("소액 사건의 4촌 이내 혈족은 충족이다", () => {
    expect(대리("청구인의 3촌 혈족").상태).toBe("충족");
    expect(대리("청구인의 4촌 이내 혈족").상태).toBe("충족");
    expect(대리("청구인의 아들").상태).toBe("충족");
  });
  it("5촌 이상은 미충족이다", () => {
    expect(대리("청구인의 5촌 혈족").상태).toBe("미충족");
  });
  it("일반 사건(청구금액도 소액 기준 이상)의 가족은 미충족이고 조문 확인 필요가 켜진다", () => {
    const 결과 = 대리("청구인의 배우자", { 사건유형: "일반", 청구금액: 90_000_000 });
    expect(결과.상태).toBe("미충족");
    expect(결과.조문확인필요).toBe(true);
  });
  it("일반 사건이지만 청구금액이 5천만원 미만이면 소액일 수 있어 판단 필요다", () => {
    expect(대리("청구인의 배우자", { 사건유형: "일반", 청구금액: 25_000_000 }).상태).toBe("판단 필요");
  });
  it("소액 사건이라 했는데 청구금액이 5천만원 이상이면 판단 필요다", () => {
    expect(대리("청구인의 배우자", { 청구금액: 50_000_000 }).상태).toBe("판단 필요");
  });
  it("청구금액 4,999만 9,999원은 소액 기준 안이다", () => {
    expect(대리("청구인의 배우자", { 청구금액: 49_999_999 }).상태).toBe("충족");
  });
});

describe("관계 없음·모호한 글", () => {
  it("관계없음으로 적히면 미충족이다", () => {
    expect(대리("청구인과 관계없음 (자격 증명 없음)").상태).toBe("미충족");
  });
  it("인척이나 법정대리처럼 분명하지 않으면 판단 필요다", () => {
    expect(대리("청구인의 며느리").상태).toBe("판단 필요");
    expect(대리("법정대리인").상태).toBe("판단 필요");
  });
  it("알 수 없는 글은 미충족으로 단정하지 않고 판단 필요다", () => {
    expect(대리("회사 직원").상태).toBe("판단 필요");
  });
});
