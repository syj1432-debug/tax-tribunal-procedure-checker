// 전체 점검과 각하 요건 해당 가능성 요약 시험
// Design Ref: §1-3 — 요약 기준
// Plan SC: PLAN 작업 9번
//
// 실행: npm test

import { describe, expect, it } from "vitest";

import 시험 from "../samples/시험사례.json";
import { 각하가능성요약, 전체점검 } from "../lib/rules";
import type { 사건정보, 상태, 점검결과 } from "../lib/types";

const 결과 = (상태: 상태): 점검결과 => ({ 항목: "청구기간", 상태, 상태뜻: "", 근거: "" });

describe("각하 요건 해당 가능성 요약", () => {
  it("하나라도 미충족이면 있음 (확인 필요가 섞여 있어도)", () => {
    expect(각하가능성요약([결과("충족"), 결과("미충족"), 결과("확인 필요"), 결과("판단 필요")])).toBe("있음");
  });
  it("모두 충족이면 없음", () => {
    expect(각하가능성요약([결과("충족"), 결과("충족"), 결과("충족"), 결과("충족")])).toBe("없음");
  });
  it("미충족은 없고 확인 필요·판단 필요가 있으면 추가 확인 필요", () => {
    expect(각하가능성요약([결과("충족"), 결과("확인 필요")])).toBe("추가 확인 필요");
    expect(각하가능성요약([결과("충족"), 결과("판단 필요")])).toBe("추가 확인 필요");
  });
});

describe("전체 점검", () => {
  it("항목 네 개가 정해진 순서로 나온다", () => {
    const 목록 = 전체점검({ 모드: "실제" });
    expect(목록.map((c) => c.항목)).toEqual(["청구기간", "처분부존재", "청구인부적격", "대리인부적격"]);
  });
  it("아무것도 입력하지 않으면 없음이 아니라 추가 확인 필요다 (빈 화면을 통과로 오해하지 않는다)", () => {
    expect(각하가능성요약(전체점검({ 모드: "실제" }))).toBe("추가 확인 필요");
  });

  const 기대요약: Record<string, string> = {
    "01-모두충족": "없음",
    "02-청구기간경과": "있음",
    "03-우편소인일규칙": "없음",
    "04-처분부존재": "있음",
    "05-처분불명확": "추가 확인 필요",
    "06-청구인다름": "추가 확인 필요",
    "07-소액-배우자대리": "없음",
    "08-소액-제3자대리": "있음",
    "09-처분일로대신계산": "없음",
  };
  for (const 사례 of 시험.사례) {
    it(`${사례.id}: 요약 ${기대요약[사례.id]}`, () => {
      const 목록 = 전체점검({ 모드: "가상", ...사례.입력 } as 사건정보);
      expect(목록.map((c) => c.상태)).toEqual([
        사례.기대.청구기간,
        사례.기대.처분부존재,
        사례.기대.청구인부적격,
        사례.기대.대리인부적격,
      ]);
      expect(각하가능성요약(목록)).toBe(기대요약[사례.id]);
    });
  }
});
