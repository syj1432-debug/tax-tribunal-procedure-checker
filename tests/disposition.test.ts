// 처분 부존재 점검 시험
// Design Ref: §3-2 — Vitest로 규칙이 맞는지 자동으로 확인한다.
// Plan SC: 네 가지 점검이 모두 충족 / 미충족 / 확인 필요 / 판단 필요 중 하나로 나온다 (PLAN 성공 기준)
//
// 실행: npm test

import { describe, expect, it } from "vitest";

import 시험 from "../samples/시험사례.json";
import { 처분부존재점검 } from "../lib/rules/disposition";
import type { 사건정보 } from "../lib/types";

const 사건 = (값: Partial<사건정보>): 사건정보 => ({ 모드: "실제", ...값 });

describe("샘플 시험 사례 (samples/시험사례.json)", () => {
  for (const 사례 of 시험.사례) {
    it(`${사례.id}: 처분 부존재 ${사례.기대.처분부존재}`, () => {
      const 결과 = 처분부존재점검({ 모드: "가상", ...사례.입력 } as 사건정보);
      expect(결과.항목).toBe("처분부존재");
      expect(결과.상태).toBe(사례.기대.처분부존재);
      expect(결과.상태뜻.length).toBeGreaterThan(0);
    });
  }

  it("처분 부존재 사례(04)는 미충족이고 조문 확인 필요 안내가 켜진다", () => {
    const 사례 = 시험.사례.find((c) => c.id === "04-처분부존재")!;
    const 결과 = 처분부존재점검({ 모드: "가상", ...사례.입력 } as 사건정보);
    expect(결과.상태).toBe("미충족");
    expect(결과.조문확인필요).toBe(true);
  });
});

describe("충족", () => {
  it("처분서가 있고 처분일·처분청이 있으면 충족이다", () => {
    const 결과 = 처분부존재점검(사건({ 처분서있음: true, 처분일: "2026-03-05", 처분청: "가상세무서" }));
    expect(결과.상태).toBe("충족");
    expect(결과.조문확인필요).toBeUndefined();
  });
});

describe("미충족 — 처분서 없음이 명시되고 처분 정보도 전혀 없을 때만", () => {
  it("처분서 없음 + 처분일·처분청 없음", () => {
    expect(처분부존재점검(사건({ 처분서있음: false })).상태).toBe("미충족");
  });
  it("공백뿐인 처분일·처분청도 없는 것으로 본다", () => {
    expect(처분부존재점검(사건({ 처분서있음: false, 처분일: "  ", 처분청: "" })).상태).toBe("미충족");
  });
  it("null로 적힌 값도 없는 것으로 본다", () => {
    expect(처분부존재점검(사건({ 처분서있음: false, 처분일: null, 처분청: null })).상태).toBe("미충족");
  });
});

describe("판단 필요 — 처분서는 없지만 처분의 흔적이 있을 때", () => {
  it("처분일만 있다", () => {
    const 결과 = 처분부존재점검(사건({ 처분서있음: false, 처분일: "2026-03-05" }));
    expect(결과.상태).toBe("판단 필요");
    expect(결과.근거).toContain("처분일 2026-03-05");
  });
  it("처분청만 있다", () => {
    const 결과 = 처분부존재점검(사건({ 처분서있음: false, 처분청: "가상세무서" }));
    expect(결과.상태).toBe("판단 필요");
    expect(결과.근거).toContain("처분청 가상세무서");
  });
  it("판단 필요 결과에는 조문 확인 필요 안내를 켜지 않는다 (미충족이 아니므로)", () => {
    expect(처분부존재점검(사건({ 처분서있음: false, 처분일: "2026-03-05" })).조문확인필요).toBeUndefined();
  });
});

describe("확인 필요 — 정보가 비어 있어 판단할 수 없을 때", () => {
  it("아무것도 입력하지 않은 빈 화면은 미충족이 아니라 확인 필요다", () => {
    expect(처분부존재점검(사건({})).상태).toBe("확인 필요");
  });
  it("처분서 유무를 입력하지 않았다 (처분일·처분청은 있음)", () => {
    expect(처분부존재점검(사건({ 처분일: "2026-03-05", 처분청: "가상세무서" })).상태).toBe("확인 필요");
  });
  it("처분서 유무가 null이다", () => {
    expect(처분부존재점검(사건({ 처분서있음: null })).상태).toBe("확인 필요");
  });
  it("처분서가 있다고 했는데 처분청이 빠졌다", () => {
    const 결과 = 처분부존재점검(사건({ 처분서있음: true, 처분일: "2026-03-05" }));
    expect(결과.상태).toBe("확인 필요");
    expect(결과.근거).toContain("처분청");
    expect(결과.근거).not.toContain("처분일,");
  });
  it("처분서가 있다고 했는데 처분일·처분청이 모두 빠졌다", () => {
    const 결과 = 처분부존재점검(사건({ 처분서있음: true }));
    expect(결과.상태).toBe("확인 필요");
    expect(결과.근거).toContain("처분일, 처분청");
  });
});
