// 자동 추출 값 정리·합치기 시험 (AI는 부르지 않는다)
// Design Ref: §2-2 — 확신이 낮은 값은 비운다. 사용자가 고친 값은 덮어쓰지 않는다.
// Plan SC: PLAN 작업 14번
//
// 실행: npm test

import { describe, expect, it } from "vitest";

import { 추출값정리, 추출값합치기, 추출칸, 파일값지우기, type AI칸값 } from "../lib/extract/fields";
import type { 사건정보 } from "../lib/types";

const 칸 = (값: string | null, 쪽수: number | null = 1, 확신: AI칸값["확신"] = "높음"): AI칸값 => ({ 값, 쪽수, 확신 });
// 모든 칸이 비어 있는 AI 답변
const 빈답변 = () => Object.fromEntries(추출칸.map((c) => [c.이름, 칸(null, null, "낮음")]));

describe("추출값정리", () => {
  it("확신이 높은 값만 담고 출처(파일명·쪽수)를 붙인다", () => {
    const 결과 = 추출값정리({ ...빈답변(), 청구인: 칸("김가상", 2), 처분청: 칸("가상세무서", 3) }, "청구서.pdf");
    expect(결과.값들).toEqual({ 청구인: "김가상", 처분청: "가상세무서" });
    expect(결과.출처.청구인).toEqual({ 파일명: "청구서.pdf", 쪽수: 2 });
    expect(결과.출처.처분청).toEqual({ 파일명: "청구서.pdf", 쪽수: 3 });
  });
  it("확신이 낮은 값은 버린다 (추측으로 채우지 않는다)", () => {
    const 결과 = 추출값정리({ ...빈답변(), 청구인: 칸("김가상", 1, "낮음") }, "a.pdf");
    expect(결과.값들).toEqual({});
  });
  it("값이 비었거나 공백이면 버린다", () => {
    const 결과 = 추출값정리({ ...빈답변(), 청구인: 칸("  "), 처분청: 칸(null) }, "a.pdf");
    expect(결과.값들).toEqual({});
  });
  it("날짜는 실제 있는 YYYY-MM-DD만 받는다", () => {
    const 결과 = 추출값정리(
      { ...빈답변(), 처분일: 칸("2026-03-05"), 접수일: 칸("2026-02-30"), 청구일: 칸("2026.04.02") },
      "a.pdf",
    );
    expect(결과.값들).toEqual({ 처분일: "2026-03-05" });
  });
  it("금액은 쉼표·원을 떼고 숫자로 바꾸며, 숫자가 아니면 버린다", () => {
    expect(추출값정리({ ...빈답변(), 청구금액: 칸("25,000,000원") }, "a.pdf").값들.청구금액).toBe(25_000_000);
    expect(추출값정리({ ...빈답변(), 청구금액: 칸("이천오백만") }, "a.pdf").값들.청구금액).toBeUndefined();
  });
  it("처분서있음은 \"예\"만 받는다. \"아니오\"는 받지 않는다 (없음은 담당자가 고른다)", () => {
    expect(추출값정리({ ...빈답변(), 처분서있음: 칸("예") }, "a.pdf").값들.처분서있음).toBe(true);
    expect(추출값정리({ ...빈답변(), 처분서있음: 칸("아니오") }, "a.pdf").값들.처분서있음).toBeUndefined();
    expect(추출값정리({ ...빈답변(), 처분서있음: 칸("모름") }, "a.pdf").값들.처분서있음).toBeUndefined();
  });
  it("글에 섞인 식별번호는 가린다", () => {
    const 결과 = 추출값정리({ ...빈답변(), 청구인: 칸("김가상 900101-1234567") }, "a.pdf");
    expect(결과.값들.청구인).not.toContain("1234567");
  });
  it("쪽수가 이상하면 쪽수 없이 파일명만 남긴다", () => {
    const 결과 = 추출값정리({ ...빈답변(), 청구인: 칸("김가상", 0) }, "a.pdf");
    expect(결과.출처.청구인).toEqual({ 파일명: "a.pdf" });
  });
  it("AI 답변이 엉뚱한 모양이어도 죽지 않고 빈 결과를 낸다", () => {
    for (const 이상한것 of [null, undefined, "글", 3, [], { 청구인: "김가상" }, { 청구인: null }]) {
      expect(추출값정리(이상한것, "a.pdf").값들).toEqual({});
    }
  });
  it("AI가 칸 목록에 없는 값을 보내도 무시한다", () => {
    const 결과 = 추출값정리({ ...빈답변(), 사건유형: 칸("소액"), 엉뚱한칸: 칸("x") }, "a.pdf");
    expect(결과.값들).toEqual({});
  });
});

describe("추출값합치기", () => {
  const 새것 = 추출값정리({ ...빈답변(), 청구인: 칸("김가상", 1), 처분청: 칸("가상세무서", 2) }, "청구서.pdf");

  it("빈 칸에 값과 출처를 채운다", () => {
    const 다음 = 추출값합치기({ 모드: "가상" }, 새것);
    expect(다음.청구인).toBe("김가상");
    expect(다음.출처?.청구인).toEqual({ 파일명: "청구서.pdf", 쪽수: 1 });
  });
  it("사용자가 직접 고친 칸은 덮어쓰지 않는다", () => {
    const 현재: 사건정보 = { 모드: "가상", 청구인: "내가고친이름", 사용자수정: ["청구인"] };
    const 다음 = 추출값합치기(현재, 새것);
    expect(다음.청구인).toBe("내가고친이름");
    expect(다음.처분청).toBe("가상세무서"); // 다른 칸은 채운다
  });
  it("사용자가 고쳐서 비워 둔 칸도 다시 채우지 않는다", () => {
    const 다음 = 추출값합치기({ 모드: "가상", 청구인: null, 사용자수정: ["청구인"] }, 새것);
    expect(다음.청구인).toBeNull();
  });
  it("이미 값이 있는 칸은 먼저 읽은 값을 둔다 (여러 파일)", () => {
    const 첫째 = 추출값합치기({ 모드: "가상" }, 새것);
    const 둘째 = 추출값정리({ ...빈답변(), 청구인: 칸("박다른", 1) }, "답변서.pdf");
    const 다음 = 추출값합치기(첫째, 둘째);
    expect(다음.청구인).toBe("김가상");
    expect(다음.출처?.청구인?.파일명).toBe("청구서.pdf");
  });
  it("원래 사건정보 객체는 바꾸지 않는다", () => {
    const 현재: 사건정보 = { 모드: "가상" };
    추출값합치기(현재, 새것);
    expect(현재.청구인).toBeUndefined();
  });
});

describe("처분서있음 합치기 (작업 18번)", () => {
  const 예 = 추출값정리({ ...빈답변(), 처분서있음: 칸("예") }, "첨부자료.pdf");

  it("AI는 있음만 채운다. 비어 있던 칸이 있음이 되고 출처가 붙는다", () => {
    const 다음 = 추출값합치기({ 모드: "가상" }, 예);
    expect(다음.처분서있음).toBe(true);
    expect(다음.출처?.처분서있음?.파일명).toBe("첨부자료.pdf");
  });
  it("담당자가 없음으로 고른 값은 AI가 있음을 읽어도 바꾸지 않는다", () => {
    const 현재: 사건정보 = { 모드: "가상", 처분서있음: false, 사용자수정: ["처분서있음"] };
    expect(추출값합치기(현재, 예).처분서있음).toBe(false);
  });
});

describe("파일값지우기", () => {
  const 청구서 = 추출값정리({ ...빈답변(), 청구인: 칸("김가상", 1), 처분청: 칸("가상세무서", 2) }, "청구서.pdf");
  const 답변서 = 추출값정리({ ...빈답변(), 접수일: 칸("2026-04-06", 1) }, "답변서.pdf");
  const 둘다 = 추출값합치기(추출값합치기({ 모드: "가상" }, 청구서), 답변서);

  it("그 파일에서 읽은 값과 출처만 지운다", () => {
    const 다음 = 파일값지우기(둘다, "청구서.pdf");
    expect(다음.청구인).toBeNull();
    expect(다음.처분청).toBeNull();
    expect(다음.출처?.청구인).toBeUndefined();
    expect(다음.접수일).toBe("2026-04-06"); // 다른 파일 값은 그대로
    expect(다음.출처?.접수일?.파일명).toBe("답변서.pdf");
  });
  it("사용자가 고친 값은 지우지 않는다", () => {
    const 고침: 사건정보 = { ...둘다, 청구인: "내가고친이름", 사용자수정: ["청구인"] };
    expect(파일값지우기(고침, "청구서.pdf").청구인).toBe("내가고친이름");
    expect(파일값지우기(고침, "청구서.pdf").처분청).toBeNull();
  });
  it("원래 객체는 바꾸지 않는다", () => {
    파일값지우기(둘다, "청구서.pdf");
    expect(둘다.청구인).toBe("김가상");
  });
});
