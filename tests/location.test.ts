// 서류상 위치 붙이기 시험
// Design Ref: §1-3 — 결과마다 서류상 위치를 보여준다
// Plan SC: PLAN 성공 기준 2번 (CHECK.md G1)
//
// 실행: npm test

import { describe, expect, it } from "vitest";

import 시험 from "../samples/시험사례.json";
import { 서류상위치글 } from "../lib/location";
import { 전체점검 } from "../lib/rules";
import type { 사건정보 } from "../lib/types";

describe("서류상위치글", () => {
  it("서류에서 읽은 값은 파일명과 쪽수를 적는다", () => {
    const 정보: 사건정보 = {
      모드: "가상",
      접수일: "2026-06-18",
      처분을안날: "2026-03-10",
      출처: { 접수일: { 파일명: "답변서.pdf", 쪽수: 2 }, 처분을안날: { 파일명: "첨부자료.pdf" } },
    };
    const 글 = 서류상위치글(정보, "청구기간");
    expect(글).toContain("접수일: 답변서.pdf 2쪽");
    expect(글).toContain("처분을 안 날: 첨부자료.pdf"); // 쪽수 없으면 파일명만
  });
  it("직접 입력한 값은 서류 위치를 모른다고 밝힌다 (실제 서류 모드)", () => {
    const 글 = 서류상위치글({ 모드: "실제", 청구인: "김가상", 처분상대방: "이다름" }, "청구인부적격");
    expect(글).toContain("청구인: 직접 입력한 값");
    expect(글).toContain("처분 상대방: 직접 입력한 값");
  });
  it("가상 모드에서 담당자가 고친 값은 읽은 출처가 아니라 직접 입력으로 적는다", () => {
    const 글 = 서류상위치글(
      { 모드: "가상", 청구인: "고친이름", 출처: { 청구인: { 파일명: "청구서.pdf", 쪽수: 1 } }, 사용자수정: ["청구인"] },
      "청구인부적격",
    );
    expect(글).toContain("직접 입력한 값");
    expect(글).not.toContain("청구서.pdf");
  });
  it("비어 있는 칸은 적지 않고, 적을 것이 없으면 undefined다", () => {
    expect(서류상위치글({ 모드: "실제" }, "청구기간")).toBeUndefined();
    expect(서류상위치글({ 모드: "실제", 접수일: "2026-06-18" }, "청구기간")).not.toContain("우편소인일");
  });
  it("파일 이름에 섞인 식별번호는 가린다", () => {
    const 글 = 서류상위치글(
      { 모드: "가상", 청구인: "김가상", 출처: { 청구인: { 파일명: "김가상_900101-1234567.pdf", 쪽수: 1 } } },
      "청구인부적격",
    );
    expect(글).not.toContain("1234567");
  });
});

describe("전체 점검에서 서류상 위치가 붙는지", () => {
  it("값이 입력된 항목에는 서류상 위치가 붙는다 (샘플 9사례, 직접 입력 기준)", () => {
    for (const 사례 of 시험.사례) {
      const 목록 = 전체점검({ 모드: "실제", ...사례.입력 } as 사건정보);
      // 청구기간·처분 부존재·청구인은 샘플마다 값이 있어서 위치가 붙어야 한다 (04번처럼 값이 거의 없는 사례 제외)
      if (사례.id === "04-처분부존재") continue;
      for (const 항목 of ["청구기간", "처분부존재", "청구인부적격"]) {
        expect(목록.find((c) => c.항목 === 항목)?.서류상위치, `${사례.id} ${항목}`).toBeTruthy();
      }
    }
  });
  it("모든 미충족 판정에 서류상 위치가 붙는다 (PLAN 성공 기준 2번)", () => {
    let 미충족수 = 0;
    for (const 사례 of 시험.사례) {
      for (const 판정 of 전체점검({ 모드: "실제", ...사례.입력 } as 사건정보)) {
        if (판정.상태 !== "미충족") continue;
        미충족수 += 1;
        expect(판정.서류상위치, `${사례.id} ${판정.항목}`).toBeTruthy();
      }
    }
    expect(미충족수).toBeGreaterThan(0);
  });
});
