// 청구인 부적격 점검 시험
// Design Ref: §3-2 — Vitest로 규칙이 맞는지 자동으로 확인한다.
// Plan SC: 네 가지 점검이 모두 충족 / 미충족 / 확인 필요 / 판단 필요 중 하나로 나온다 (PLAN 성공 기준)
//
// 실행: npm test

import { describe, expect, it } from "vitest";

import 시험 from "../samples/시험사례.json";
import { 청구인부적격점검 } from "../lib/rules/claimant";
import type { 사건정보 } from "../lib/types";

const 사건 = (값: Partial<사건정보>): 사건정보 => ({ 모드: "실제", ...값 });

describe("샘플 시험 사례 (samples/시험사례.json)", () => {
  for (const 사례 of 시험.사례) {
    it(`${사례.id}: 청구인 부적격 ${사례.기대.청구인부적격}`, () => {
      const 결과 = 청구인부적격점검({ 모드: "가상", ...사례.입력 } as 사건정보);
      expect(결과.항목).toBe("청구인부적격");
      expect(결과.상태).toBe(사례.기대.청구인부적격);
      expect(결과.상태뜻.length).toBeGreaterThan(0);
    });
  }
});

describe("충족", () => {
  it("청구인과 처분 상대방이 같다", () => {
    expect(청구인부적격점검(사건({ 청구인: "김가상", 처분상대방: "김가상" })).상태).toBe("충족");
  });
  it("앞뒤·연속 공백만 다르면 같다고 본다", () => {
    expect(청구인부적격점검(사건({ 청구인: " 가상물산  주식회사 ", 처분상대방: "가상물산 주식회사" })).상태).toBe("충족");
  });
});

describe("판단 필요 — 다르면 미충족이 아니라 판단 필요", () => {
  it("이름이 다르면 판단 필요이고 사유에 두 이름과 예외 조문이 나온다", () => {
    const 결과 = 청구인부적격점검(사건({ 청구인: "가상물산 주식회사", 처분상대방: "가상상사 주식회사" }));
    expect(결과.상태).toBe("판단 필요");
    expect(결과.근거).toContain("가상물산 주식회사");
    expect(결과.근거).toContain("가상상사 주식회사");
    expect(결과.근거).toContain("제55조 제2항");
  });
  it("비슷해 보여도 글자가 다르면 같다고 추측하지 않는다", () => {
    expect(청구인부적격점검(사건({ 청구인: "(주)가상물산", 처분상대방: "가상물산 주식회사" })).상태).toBe("판단 필요");
  });
  it("미충족을 내지 않는다", () => {
    expect(청구인부적격점검(사건({ 청구인: "갑", 처분상대방: "을" })).조문확인필요).toBeUndefined();
  });
});

describe("확인 필요 — 대조할 값이 없을 때", () => {
  it("빈 화면", () => {
    expect(청구인부적격점검(사건({})).상태).toBe("확인 필요");
  });
  it("처분 상대방이 없다", () => {
    const 결과 = 청구인부적격점검(사건({ 청구인: "김가상" }));
    expect(결과.상태).toBe("확인 필요");
    expect(결과.근거).toContain("처분 상대방");
  });
  it("청구인이 없다", () => {
    const 결과 = 청구인부적격점검(사건({ 처분상대방: "김가상" }));
    expect(결과.상태).toBe("확인 필요");
    expect(결과.근거).toContain("청구인");
  });
  it("공백뿐이거나 null이면 없는 것으로 본다", () => {
    expect(청구인부적격점검(사건({ 청구인: "  ", 처분상대방: null })).상태).toBe("확인 필요");
  });
});
