// 식별번호 가리기(마스킹)
// Design Ref: §4 — 화면에 글자로 표시하기 전에 이 파일을 거친다. 식별번호 입력 칸은 두지 않는다.
// Plan SC: PLAN 작업 10번 — 화면에 나오는 주민등록번호 같은 식별번호가 가려져 있다.
// 예외: 가상 서류 원본 보기는 지어낸 번호이므로 가리지 않는다. (DESIGN §1-3)
//
// 가리는 번호
//  - 주민등록번호·외국인등록번호·법인등록번호: 숫자 6자리-7자리 (하이픈·공백 없이 13자리 이어진 것도)
//  - 사업자등록번호: 숫자 3자리-2자리-5자리
// 모양이 같은 번호는 종류를 구분하지 않고 모두 가린다. 점검에는 번호가 필요 없기 때문이다.
// 번호의 일부(앞자리 등)도 남기지 않는다. 생년월일 같은 정보가 새지 않게 하기 위해서다.

const 가림표시 = "[식별번호 가림]";

// 앞뒤가 숫자인 경우(더 긴 숫자의 일부)는 건드리지 않도록 경계를 둔다.
const 주민등록번호모양 = /(?<!\d)\d{6}[-\s]?\d{7}(?!\d)/g;
const 사업자등록번호모양 = /(?<!\d)\d{3}-\d{2}-\d{5}(?!\d)/g;

/** 글자 안의 식별번호를 가린다. 번호가 없으면 그대로 돌려준다. */
export function 마스킹(글: string): string {
  return 글.replace(주민등록번호모양, 가림표시).replace(사업자등록번호모양, 가림표시);
}

/** 값이 비어 있을 수 있는 경우를 위한 짝. null·undefined는 그대로 돌려준다. */
export function 마스킹또는없음(글: string | null | undefined): string | null | undefined {
  return typeof 글 === "string" ? 마스킹(글) : 글;
}
