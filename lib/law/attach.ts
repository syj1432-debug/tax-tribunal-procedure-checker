// 점검 결과에 근거 조문 붙이기
// Design Ref: §2-3 — 미충족이 나오면 조문 파일에서 근거 조문을 읽어 붙이고, 파일에 없으면 "조문 확인 필요"로 표시한다.
// Plan SC: PLAN 작업 16번 — 미충족 판정마다 근거 조문(원문, 주소, 확인 날짜)이 함께 보인다.
//
// 어떤 판정에 어떤 조문을 붙일지는 여기서 정한다. 조문 원문은 articles.ts에 있는 것만 쓴다.
// 필요한 조문이 파일에 없으면(예: 민법 제157조) 그 이름을 "확인필요조문"에 담아 화면에 "조문 확인 필요"로 보여준다.

import type { 점검결과 } from "../types";
import { 조문목록 } from "./articles";

// 미충족 판정에 붙이는 조문 (위에서부터 보여준다)
const 미충족조문: Record<점검결과["항목"], string[]> = {
  청구기간: [
    "국세기본법 제68조", // 청구기간 90일
    "국세기본법 제5조", // 말일이 휴일이면 다음 날
    "국세기본법 제5조의2", // 우편날짜도장이 찍힌 날
    "국세기본법 제61조", // 기한까지 우편으로 낸 청구서가 늦게 도달해도 적법 (제80조의2로 준용)
    "국세기본법 제80조의2", // 심판청구에 제61조·제65조 준용
    "국세기본법 제65조", // 청구기간이 지난 청구는 각하
    "민법 제157조", // 기간의 초일 불산입 — 아직 조문 파일에 없음
  ],
  처분부존재: ["국세기본법 제55조", "국세기본법 제80조의2", "국세기본법 제65조"],
  청구인부적격: ["국세기본법 제55조", "국세기본법 제80조의2", "국세기본법 제65조"],
  대리인부적격: ["국세기본법 제59조", "국세기본법 시행령 제62조", "국세기본법 제80조의2", "국세기본법 제65조"],
};

// 판단 필요일 때도 판단 기준이 되는 조문을 보여주는 항목
const 판단필요조문: Partial<Record<점검결과["항목"], string[]>> = {
  청구인부적격: ["국세기본법 제55조"], // 처분을 받은 자가 아니어도 청구할 수 있는 경우(제2항)
  대리인부적격: ["국세기본법 제59조", "국세기본법 시행령 제62조"],
};

/**
 * 결과에 근거 조문을 붙인다. 원래 결과는 바꾸지 않고 새 결과를 돌려준다.
 *  - 미충족: 항목별 조문 전부
 *  - 판단 필요(청구인·대리인): 판단 기준 조문
 *  - 그 밖의 상태는 조문을 붙이지 않는다.
 * 조문 파일에 없는 조문은 "확인필요조문"에 담고 "조문확인필요"를 켠다. 모두 있으면 "조문확인필요"를 끈다.
 */
export function 근거조문붙이기(결과: 점검결과): 점검결과 {
  const 키들 =
    결과.상태 === "미충족" ? 미충족조문[결과.항목] : 결과.상태 === "판단 필요" ? (판단필요조문[결과.항목] ?? []) : [];
  if (키들.length === 0) return 결과;

  const 있는것 = 키들.filter((키) => 키 in 조문목록);
  const 없는것 = 키들.filter((키) => !(키 in 조문목록));
  const { 조문확인필요: _이전표시, ...나머지 } = 결과;
  void _이전표시;

  return {
    ...나머지,
    근거조문: 있는것.map((키) => ({ ...조문목록[키], 이름: 키 })),
    ...(없는것.length > 0 ? { 조문확인필요: true, 확인필요조문: 없는것 } : {}),
  };
}
