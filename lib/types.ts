// 사건 정보의 공통 모양
// Design Ref: §2-5 — 입력 화면, 점검 규칙 4개, 결과 화면, 자동 추출이 모두 이 모양을 함께 쓴다.
// Plan SC: PLAN 작업 1번 — 사건 정보의 공통 모양 정하기
//
// 이 파일에는 두 가지 공통 모양이 있다.
//   1) 사건정보 — 사용자가 입력하거나 서류에서 뽑은 값 (PLAN 작업 1번)
//   2) 점검결과 — 점검 규칙 4개가 돌려주는 결과 (PLAN 작업 2번, 파일 아래쪽)

/** 어떤 서류로 점검하는지. 시작 화면에서 고른다. (DESIGN §1-1) */
export type 모드 = "가상" | "실제";

/** 사건 유형. 소액 여부는 청구금액으로 함께 확인한다. (PRD 5번 대리인 부적격 규칙) */
export type 사건유형 = "소액" | "일반";

/**
 * 날짜 문자열. 항상 "YYYY-MM-DD" 모양이다. (예: "2026-03-10")
 * 값이 서류에 없으면 아래 사건정보에서 비워 둔다(null 또는 생략).
 */
export type 날짜문자열 = string;

/** 가상 서류 모드에서 값을 어느 파일 몇 쪽에서 뽑았는지. (PRD 5번: 추출값마다 출처 표시) */
export interface 출처정보 {
  파일명: string;
  쪽수?: number;
}

/**
 * 사건 정보
 *
 * - 모든 값은 비어 있을 수 있다. 비어 있다는 것(null 또는 생략)은 "서류에 없음"이라는 뜻이고,
 *   점검할 때 "확인 필요"로 이어진다. 추측으로 채우지 않는다. (DESIGN 설계 원칙 4)
 * - samples/시험사례.json의 "입력"은 null로 "서류에 없음"을 적는다. 그래서 null도 함께 허용한다.
 * - 식별번호(주민등록번호 등)는 점검에 필요하지 않으므로 칸을 두지 않는다. (PRD 7번)
 */
export interface 사건정보 {
  모드: 모드;

  // ── 사건 종류 ──
  사건유형?: 사건유형 | null;
  /** 청구금액(원). 소액 여부 확인용 */
  청구금액?: number | null;

  // ── 날짜 ──
  /** 청구서에 적힌 날짜. 참고용이며 청구기간 판정에는 쓰지 않는다. (PRD 5번, 열린 질문 10번) */
  청구일?: 날짜문자열 | null;
  우편소인일?: 날짜문자열 | null;
  /** 조세심판원 접수일 */
  접수일?: 날짜문자열 | null;
  처분일?: 날짜문자열 | null;
  /** 청구기간의 기산 기준. 없으면 처분일로 대신 계산하고 "추정"을 표시한다. */
  처분을안날?: 날짜문자열 | null;

  // ── 처분 ──
  처분청?: string | null;
  /** 처분서(납세고지서 등)가 서류에 있는지 */
  처분서있음?: boolean | null;
  /** 납세고지서 수신자 등. 청구인과 대조해 청구인 부적격을 점검한다. */
  처분상대방?: string | null;

  // ── 사람 ──
  청구인?: string | null;
  대리인?: string | null;
  /** 대리인과 청구인의 관계·자격. 예: "청구인의 배우자" */
  대리인관계자격?: string | null;

  // ── 가상 서류 모드에서만 쓰는 값 ──
  /** 값 이름 → 출처. 예: { 처분일: { 파일명: "청구서.pdf", 쪽수: 1 } } */
  출처?: Partial<Record<값이름, 출처정보>>;
  /** 사용자가 직접 고친 값의 이름. 다시 추출해도 이 값은 덮어쓰지 않는다. (PRD 5번) */
  사용자수정?: 값이름[];
}

/** 사건정보에서 "값"에 해당하는 칸의 이름들. (모드·출처·사용자수정은 값이 아니다) */
export type 값이름 = Exclude<keyof 사건정보, "모드" | "출처" | "사용자수정">;

// ───────────────────────── 점검 결과 (PLAN 작업 2번) ─────────────────────────

/** 점검 항목 네 가지. (PRD 5번) 항목 이름은 문제가 있는 쪽을 가리키므로 "충족"은 "그 문제가 없다"는 뜻이다. */
export type 점검항목 = "청구기간" | "처분부존재" | "청구인부적격" | "대리인부적격";

/**
 * 점검 결과 상태 네 가지. (PRD 5번, DESIGN §1-3)
 * - 충족: 요건을 갖춘 것으로 확인됨
 * - 미충족: 요건을 갖추지 못한 것으로 확인됨
 * - 확인 필요: 판단에 필요한 정보(서류, 또는 공휴일 목록·조문 파일 같은 기준 자료)가 없음
 * - 판단 필요: 정보는 있으나 해석이 어려워 담당자의 판단이 필요함
 */
export type 상태 = "충족" | "미충족" | "확인 필요" | "판단 필요";

/**
 * 상태 옆에 함께 표시하는 뜻. (DESIGN §1-3 표)
 * 항목 이름("청구기간 경과" 등)이 문제 있는 쪽을 가리켜서 "충족"이 거꾸로 읽히지 않게 하기 위함이다.
 */
export const 상태뜻: Record<상태, string> = {
  충족: "각하 사유 아님",
  미충족: "각하 사유 해당 가능",
  "확인 필요": "결과 확정 전",
  "판단 필요": "결과 확정 전",
};

/** 근거 조문 한 건. law.go.kr에서 확인한 조문을 파일에 담아 쓴다. (DESIGN §2-3) */
export interface 조문정보 {
  /** 조문 이름. 예: 국세기본법 제68조 */
  이름?: string;
  /** 조문 원문 */
  원문: string;
  /** law.go.kr 주소 */
  주소: string;
  /** 확인한 날짜 (YYYY-MM-DD) */
  확인날짜: 날짜문자열;
}

/** 점검 항목 하나의 결과. 규칙 4개가 모두 이 모양으로 돌려준다. (DESIGN §2-5) */
export interface 점검결과 {
  항목: 점검항목;
  상태: 상태;
  /** 상태 옆에 함께 표시하는 뜻. 보통 상태뜻[상태]를 쓴다. */
  상태뜻: string;
  /** 사람이 읽는 설명 */
  근거: string;
  /** 청구기간용. 기산일·기한일 계산 과정, "청구일로 보는 날", "추정" 표시를 담는다. */
  계산과정?: string;
  /** 조문 파일에서 읽은 근거 조문. 미충족 판정에 붙는다. */
  근거조문?: 조문정보[];
  /**
   * 조문 파일에 해당 조문이 없을 때 true. "조문 확인 필요"라는 안내 문구를 띄우는 표시다.
   * 판정 상태가 아니다. (PRD 5번, DESIGN §2-3)
   */
  조문확인필요?: boolean;
  /** 조문 파일에 아직 없어 "조문 확인 필요"로 보여줄 조문 이름들 */
  확인필요조문?: string[];
  /** 서류에서 근거를 찾은 위치. 예: "청구서.pdf 1쪽" */
  서류상위치?: string;
}
