// 청구인 부적격 점검
// Design Ref: §2-4 — 판정은 같은 입력이면 항상 같은 결과가 나오는 규칙 코드로 만든다. (AI를 쓰지 않는다)
// Plan SC: PLAN 작업 7번 — 청구인이 처분 상대방(납세고지서 수신자 등)과 다르면 "판단 필요"로 사유 표시
//
// 근거 (2026-11-20 www.law.go.kr에서 확인):
//  - 국세기본법 제55조 제1항: 이 법 또는 세법에 따른 처분으로 권리나 이익을 침해당한 자가 심판청구를 할 수 있다.
//  - 국세기본법 제55조 제2항: 처분을 받은 자가 아니어도 권리나 이익을 침해당하게 될 이해관계인으로서
//    다음에 해당하는 자는 그 처분에 대해 청구할 수 있다.
//      1. 제2차 납세의무자로서 납부고지서를 받은 자
//      2. 제42조에 따라 물적납세 의무를 지는 자로서 납부고지서를 받은 자 (2의2·2의3: 부가가치세법·종합부동산세법상 물적납세의무자)
//      3. 보증인
//      4. 그 밖에 대통령령으로 정하는 자
//
// 판정 기준 (이 파일이 정한 해석)
//  - 충족    : 청구인과 처분 상대방이 같다. (공백만 정리해 비교한다)
//  - 판단 필요: 청구인과 처분 상대방이 다르다. 예외(제55조 제2항)에 해당할 수 있어 "미충족"으로 단정하지 않는다.
//  - 확인 필요: 청구인 또는 처분 상대방이 비어 있어 대조할 수 없다.
//  - 이름이 비슷해 보여도 글자가 다르면 같다고 추측하지 않고 "판단 필요"로 둔다. (AI·유사도 추측을 쓰지 않는다)
//
// 조문 원문을 보여주는 "조문 파일"은 PLAN 작업 16번에서 만든다.

import type { 사건정보, 점검결과 } from "../types";
import { 상태뜻 } from "../types";

function 글자있음(값: string | null | undefined): 값 is string {
  return typeof 값 === "string" && 값.trim() !== "";
}

// 앞뒤 공백을 없애고 연속 공백을 하나로 줄인다. (그 밖의 글자는 바꾸지 않는다)
function 정리(값: string): string {
  return 값.trim().replace(/\s+/g, " ");
}

function 결과만들기(상태: 점검결과["상태"], 근거: string): 점검결과 {
  return {
    항목: "청구인부적격",
    상태,
    상태뜻: 상태뜻[상태],
    근거,
  };
}

export function 청구인부적격점검(정보: 사건정보): 점검결과 {
  const 청구인있음 = 글자있음(정보.청구인);
  const 상대방있음 = 글자있음(정보.처분상대방);

  if (!청구인있음 || !상대방있음) {
    const 빠진것 = [!청구인있음 && "청구인", !상대방있음 && "처분 상대방"].filter(Boolean).join(", ");
    return 결과만들기(
      "확인 필요",
      `${빠진것}이(가) 입력되지 않아 청구인이 처분의 상대방인지 대조할 수 없다. 서류에서 확인해야 한다.`,
    );
  }

  const 청구인 = 정리(정보.청구인 as string);
  const 상대방 = 정리(정보.처분상대방 as string);

  if (청구인 === 상대방) {
    return 결과만들기("충족", `청구인(${청구인})이 처분 상대방과 같아 청구 자격이 있다.`);
  }

  return 결과만들기(
    "판단 필요",
    `청구인(${청구인})이 처분 상대방(${상대방})과 다르다. ` +
      "처분을 받은 자가 아니어도 제2차 납세의무자·물적납세의무자로서 납부고지서를 받은 자, 보증인 등은 " +
      "청구할 수 있으므로(국세기본법 제55조 제2항) 청구인이 여기에 해당하는지 담당자가 판단해야 한다.",
  );
}
