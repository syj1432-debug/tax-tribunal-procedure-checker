// 처분 부존재 점검
// Design Ref: §2-4 — 판정은 같은 입력이면 항상 같은 결과가 나오는 규칙 코드로 만든다. (AI를 쓰지 않는다)
// Plan SC: PLAN 작업 6번 — 대상 처분이 확인되지 않으면 미충족, 판단이 어려우면 "판단 필요"
//
// 보는 정보는 PRD 5번이 정한 세 가지뿐이다: 처분서 유무, 처분일, 처분청.
// (처분을 안 날·처분 상대방은 다른 점검 항목에서 쓰므로 여기서는 보지 않는다.)
//
// 판정 기준 (이 파일이 정한 해석이며, 사례 04·05와 맞춰 만들었다)
//  - 미충족  : 처분서가 "없음"이라고 입력됐고, 처분일과 처분청도 모두 없다. → 대상 처분이 어디에도 확인되지 않는다.
//  - 판단 필요: 처분서는 "없음"인데 처분일이나 처분청 중 하나라도 있다. → 처분의 흔적은 있으나 처분인지 서류만으로 분명하지 않다.
//  - 충족    : 처분서가 "있음"이고 처분일과 처분청이 모두 있다.
//  - 확인 필요: 그 밖에 정보가 비어 있어 판단할 수 없다. (처분서 유무를 입력하지 않았거나, "있음"인데 처분일·처분청이 빠진 경우)
//    → 아직 입력하지 않은 빈 화면을 "처분 없음"으로 오해하지 않기 위해, 미충족은 "없음"이 명시됐을 때만 낸다.
//
// 근거 조문을 보여주는 "조문 파일"은 PLAN 작업 16번에서 만든다. 그래서 미충족 결과에는 "조문확인필요"를 켠다.

import type { 사건정보, 점검결과 } from "../types";
import { 상태뜻 } from "../types";

// 비어 있거나 공백뿐인 글자는 "없음"으로 본다.
function 글자있음(값: string | null | undefined): 값 is string {
  return typeof 값 === "string" && 값.trim() !== "";
}

function 결과만들기(상태: 점검결과["상태"], 근거: string): 점검결과 {
  return {
    항목: "처분부존재",
    상태,
    상태뜻: 상태뜻[상태],
    근거,
    // 조문 파일은 작업 16번에서 만든다. 그때까지 미충족에는 "조문 확인 필요" 안내를 켠다.
    ...(상태 === "미충족" ? { 조문확인필요: true } : {}),
  };
}

export function 처분부존재점검(정보: 사건정보): 점검결과 {
  const 처분서 = 정보.처분서있음; // true | false | null | undefined
  const 처분일있음 = 글자있음(정보.처분일);
  const 처분청있음 = 글자있음(정보.처분청);

  // 처분서 유무를 입력하지 않았다. (빈 화면과 "처분 없음"을 구분하기 위해 미충족을 내지 않는다)
  if (처분서 === null || 처분서 === undefined) {
    return 결과만들기(
      "확인 필요",
      "처분서가 서류에 있는지 입력되지 않아 처분이 있는지 판단할 수 없다. 처분서 유무를 확인해야 한다.",
    );
  }

  if (처분서 === true) {
    if (처분일있음 && 처분청있음) {
      return 결과만들기("충족", "처분서가 있고 처분일·처분청이 확인되어 대상 처분이 존재한다.");
    }
    const 빠진것 = [!처분일있음 && "처분일", !처분청있음 && "처분청"].filter(Boolean).join(", ");
    return 결과만들기(
      "확인 필요",
      `처분서가 있다고 하나 ${빠진것}이(가) 입력되지 않아 대상 처분을 특정할 수 없다. 처분서에서 확인해야 한다.`,
    );
  }

  // 처분서가 "없음"으로 입력된 경우
  if (!처분일있음 && !처분청있음) {
    return 결과만들기("미충족", "처분서가 없고 처분일·처분청도 확인되지 않아 대상 처분이 확인되지 않는다.");
  }

  const 확인된것 = [처분일있음 && `처분일 ${정보.처분일}`, 처분청있음 && `처분청 ${정보.처분청}`]
    .filter(Boolean)
    .join(", ");
  return 결과만들기(
    "판단 필요",
    `처분서는 없으나 ${확인된것}이(가) 있어, 처분이 있었는지 서류만으로 분명하지 않다. 담당자가 판단해야 한다.`,
  );
}
