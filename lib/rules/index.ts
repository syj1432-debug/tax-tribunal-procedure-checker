// 점검 규칙 네 개를 한꺼번에 돌리고, 각하 요건 해당 가능성을 요약한다.
// Design Ref: §1-3 — "각하 요건 해당 가능성" 요약 기준
// Plan SC: PLAN 작업 9번 — 네 항목 상태와 각하 요건 해당 가능성 표시 (AI를 쓰지 않는다)

import type { 사건정보, 점검결과 } from "../types";
import { 근거조문붙이기 } from "../law/attach";
import { 서류상위치붙이기 } from "../location";
import { 대리인부적격점검 } from "./agent";
import { 청구인부적격점검 } from "./claimant";
import { 처분부존재점검 } from "./disposition";
import { 청구기간점검 } from "./period";

export type 각하가능성 = "있음" | "없음" | "추가 확인 필요";

/** 네 가지 점검을 화면에 보여줄 순서대로 돌려준다. (청구기간 → 처분 부존재 → 청구인 → 대리인) 근거 조문(작업 16번)과 서류상 위치(CHECK.md G1)도 붙인다. */
export function 전체점검(정보: 사건정보): 점검결과[] {
  return [청구기간점검(정보), 처분부존재점검(정보), 청구인부적격점검(정보), 대리인부적격점검(정보)].map((결과) =>
    서류상위치붙이기(근거조문붙이기(결과), 정보),
  );
}

/**
 * 각하 요건 해당 가능성 요약 (DESIGN §1-3)
 *  - 하나라도 미충족 → 있음
 *  - 모두 충족 → 없음
 *  - 그 외(확인 필요·판단 필요가 있고 미충족은 없음) → 추가 확인 필요
 */
export function 각하가능성요약(결과들: 점검결과[]): 각하가능성 {
  if (결과들.some((결과) => 결과.상태 === "미충족")) return "있음";
  if (결과들.every((결과) => 결과.상태 === "충족")) return "없음";
  return "추가 확인 필요";
}
