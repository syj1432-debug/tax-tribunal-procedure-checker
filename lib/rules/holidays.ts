// 공휴일 목록 (직접 관리)
// Design Ref: §5-5 — 공휴일을 파일 하나에 직접 적어 관리한다. 목록에 없는 연도는 "알 수 없음"으로 돌려준다.
//
// 근거 (2026-11-20 www.law.go.kr에서 확인):
//  - 국세기본법 제5조 제1항: 기한이 토요일·일요일, 「공휴일에 관한 법률」에 따른 공휴일 및 대체공휴일,
//    「노동절 제정에 관한 법률」에 따른 노동절이면 그 다음날을 기한으로 한다.
//  - 공휴일에 관한 법률 제2조: 국경일, 1월 1일, 설날 연휴, 부처님 오신 날, 노동절(5월 1일), 어린이날,
//    현충일, 추석 연휴, 기독탄신일, 임기 만료 선거일 등.
//  - 관공서의 공휴일에 관한 규정 제3조: 대체공휴일(공휴일이 토·일요일 등과 겹칠 때 그 다음 첫 비공휴일).
//
// 관리 방법: 매년 말에 다음 해 공휴일을 이 표에 추가한다. 임시공휴일이 새로 지정되면 해당 연도에 추가한다.
// 표에 없는 연도의 평일은 휴일인지 알 수 없으므로 점검 결과를 "확인 필요"로 둔다. (추측으로 채우지 않는다.)

import type { 날짜문자열 } from "../types";
import { 요일번호 } from "./dates";

/** 연도 → (날짜 → 휴일 이름). 토·일요일은 적지 않는다. (요일로 판단) */
const 공휴일표: Record<number, Record<날짜문자열, string>> = {
  2026: {
    "2026-01-01": "신정",
    "2026-02-16": "설날 전날",
    "2026-02-17": "설날",
    "2026-02-18": "설날 다음 날",
    "2026-03-02": "삼일절 대체공휴일", // 3월 1일이 일요일
    "2026-05-01": "노동절",
    "2026-05-05": "어린이날",
    "2026-05-25": "부처님 오신 날 대체공휴일", // 5월 24일이 일요일
    "2026-06-03": "전국동시지방선거일",
    "2026-07-17": "제헌절",
    "2026-08-17": "광복절 대체공휴일", // 8월 15일이 토요일
    "2026-09-24": "추석 전날",
    "2026-09-25": "추석",
    "2026-10-05": "개천절 대체공휴일", // 10월 3일이 토요일, 10월 4일은 일요일
    "2026-10-09": "한글날",
    "2026-12-25": "기독탄신일",
    // 토요일·일요일과 겹친 날은 요일로 판단하므로 적지 않았다:
    // 삼일절(3/1 일), 부처님 오신 날(5/24 일), 현충일(6/6 토, 대체공휴일 없음), 광복절(8/15 토),
    // 추석 다음 날(9/26 토), 개천절(10/3 토)
  },
};

/** 이 해의 공휴일 목록이 들어 있는지 */
export function 확인된연도(연도: number): boolean {
  return 연도 in 공휴일표;
}

export type 휴일판정 =
  | { 결과: "휴일"; 이유: string }
  | { 결과: "평일" }
  | { 결과: "알수없음"; 이유: string };

/**
 * 그 날이 "기한을 미루는 날"(토·일요일, 공휴일, 대체공휴일, 노동절)인지 판정한다.
 * 토·일요일은 연도와 상관없이 휴일이다. 평일은 그 연도의 목록이 있어야 판정할 수 있다.
 */
export function 휴일인지(값: 날짜문자열): 휴일판정 {
  const 요일 = 요일번호(값);
  if (요일 === 6) return { 결과: "휴일", 이유: "토요일" };
  if (요일 === 0) return { 결과: "휴일", 이유: "일요일" };

  const 연도 = Number(값.slice(0, 4));
  if (!확인된연도(연도)) {
    return { 결과: "알수없음", 이유: `${연도}년 공휴일 목록이 없음` };
  }
  const 이름 = 공휴일표[연도][값];
  return 이름 ? { 결과: "휴일", 이유: 이름 } : { 결과: "평일" };
}
