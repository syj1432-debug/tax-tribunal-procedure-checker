// 청구기간 경과 점검
// Design Ref: §2-4 — 판정은 같은 입력이면 항상 같은 결과가 나오는 규칙 코드로 만든다. (AI를 쓰지 않는다)
// Plan SC: PLAN 작업 5번 — 민법 기간 계산, 90일 판단, 우편소인일 규칙, 처분일로 대신 계산 시 "추정" 표시, 계산 과정 표시
//
// 근거 (2026-11-20 www.law.go.kr에서 확인):
//  - 국세기본법 제68조 제1항: 심판청구는 처분이 있음을 안 날(처분의 통지를 받은 때에는 그 받은 날)부터 90일 이내.
//  - 민법 제157조: 기간을 일로 정한 때에는 기간의 초일은 산입하지 않는다. (안 날의 다음 날이 기산일)
//  - 국세기본법 제5조 제1항: 기한이 토·일요일, 공휴일·대체공휴일, 노동절이면 그 다음날을 기한으로 한다.
//    (민법 제155조: 법령에 다른 정한 바가 없으면 민법의 기간 계산을 따른다. 말일 특례는 이 법이 따로 정했다.)
//  - 국세기본법 제61조 제3항(제80조의2로 심판청구에 준용): 기한까지 우편으로 제출한 청구서가 청구기간을 지나서
//    도달한 경우에는 그 기간의 만료일에 적법한 청구를 한 것으로 본다. 우편 제출일은 제5조의2 제1항에 따라
//    우편날짜도장이 찍힌 날을 기준으로 한다.
//
// 조문 원문을 보여주는 "조문 파일"은 PLAN 작업 16번에서 만든다. 그래서 미충족 결과에는 "조문확인필요"를 켠다.

import type { 사건정보, 점검결과 } from "../types";
import { 상태뜻 } from "../types";
import { 올바른날짜, 요일붙이기, 일수더하기 } from "./dates";
import { 휴일인지 } from "./holidays";

const 청구기간일수 = 90;

type 읽은값 = { 상태: "없음" } | { 상태: "잘못됨"; 값: string } | { 상태: "있음"; 값: string };

// 비어 있으면 "없음", 날짜 모양이 아니면 "잘못됨"으로 구분한다.
function 읽기(값: string | null | undefined): 읽은값 {
  if (값 === null || 값 === undefined || 값.trim() === "") return { 상태: "없음" };
  return 올바른날짜(값) ? { 상태: "있음", 값 } : { 상태: "잘못됨", 값 };
}

function 결과만들기(
  상태: 점검결과["상태"],
  근거: string,
  계산과정: string[],
): 점검결과 {
  return {
    항목: "청구기간",
    상태,
    상태뜻: 상태뜻[상태],
    근거,
    계산과정: 계산과정.join("\n"),
    // 조문 파일은 작업 16번에서 만든다. 그때까지 미충족에는 "조문 확인 필요" 안내를 켠다.
    ...(상태 === "미충족" ? { 조문확인필요: true } : {}),
  };
}

export function 청구기간점검(정보: 사건정보): 점검결과 {
  const 안날 = 읽기(정보.처분을안날);
  const 처분일 = 읽기(정보.처분일);
  const 접수 = 읽기(정보.접수일);
  const 소인 = 읽기(정보.우편소인일);

  // 1) 날짜 모양이 잘못된 값이 있으면 계산하지 않는다.
  const 확인대상: [string, 읽은값][] = [
    ["처분을 안 날", 안날],
    ["처분일", 처분일],
    ["접수일", 접수],
    ["우편소인일", 소인],
  ];
  const 잘못된것 = 확인대상.flatMap(([이름, 값]) => (값.상태 === "잘못됨" ? [`${이름} "${값.값}"`] : []));
  if (잘못된것.length > 0) {
    return 결과만들기("확인 필요", `날짜 형식(YYYY-MM-DD)이 올바르지 않아 계산할 수 없다: ${잘못된것.join(", ")}`, []);
  }

  // 2) 기준 날짜: 처분을 안 날. 없으면 처분일로 대신 계산하고 "추정"을 표시한다.
  let 기준일: string;
  let 추정 = false;
  if (안날.상태 === "있음") {
    기준일 = 안날.값;
  } else if (처분일.상태 === "있음") {
    기준일 = 처분일.값;
    추정 = true;
  } else {
    return 결과만들기("확인 필요", "처분을 안 날과 처분일이 모두 없어 청구기간을 계산할 수 없다.", []);
  }

  const 접수일 = 접수.상태 === "있음" ? 접수.값 : null;
  const 소인일 = 소인.상태 === "있음" ? 소인.값 : null;
  if (접수일 === null && 소인일 === null) {
    return 결과만들기("확인 필요", "접수일과 우편소인일이 모두 없어 청구기간을 판단할 수 없다.", []);
  }

  // 3) 기간 계산: 초일 불산입(기산일 = 기준일 다음 날), 90일째가 기간 말일.
  const 기산일 = 일수더하기(기준일, 1);
  const 말일 = 일수더하기(기준일, 청구기간일수);
  const 과정 = [
    추정
      ? `처분을 안 날이 없어 처분일 ${요일붙이기(기준일)}을 기준으로 계산한다. (추정)`
      : `처분을 안 날: ${요일붙이기(기준일)}`,
    `기산일: ${요일붙이기(기산일)} (초일 불산입, 민법 제157조)`,
    `기간 말일: ${요일붙이기(말일)} (${청구기간일수}일째, 국세기본법 제68조 제1항)`,
  ];

  // 4) 기한: 말일이 토·일요일, 공휴일 등이면 휴일이 끝난 다음날로 미룬다. (국세기본법 제5조 제1항)
  //    연휴가 이어지면 휴일이 끝날 때까지 계속 다음날로 간다.
  let 기한: string | null = 말일;
  const 미룬이유: string[] = [];
  while (기한 !== null) {
    const 판정 = 휴일인지(기한);
    if (판정.결과 === "평일") break;
    if (판정.결과 === "알수없음") {
      기한 = null;
      과정.push(`기한: 정할 수 없음 (${판정.이유}). 공휴일 목록에 해당 연도를 추가해야 한다.`);
      break;
    }
    미룬이유.push(`${요일붙이기(기한)} ${판정.이유}`);
    기한 = 일수더하기(기한, 1);
  }
  if (기한 !== null) {
    과정.push(
      미룬이유.length === 0
        ? `기한: ${요일붙이기(기한)} (말일이 휴일이 아님)`
        : `기한: ${요일붙이기(기한)} (말일이 휴일이라 다음날로 미룸: ${미룬이유.join(" → ")}, 국세기본법 제5조 제1항)`,
    );
  }

  const 추정표시 = 추정 ? " (추정: 처분일 기준)" : "";
  const 입력과정 = [
    `접수일: ${접수일 ? 요일붙이기(접수일) : "(없음)"}`,
    `우편소인일: ${소인일 ? 요일붙이기(소인일) : "(없음)"}`,
  ];

  // 5-1) 접수일이 원래 말일 이내면, 휴일 여부와 상관없이 기한 이내다.
  if (접수일 !== null && 접수일 <= 말일) {
    return 결과만들기("충족", `접수일이 기간 말일 이내라 청구기간을 지켰다.${추정표시}`, [...과정, ...입력과정]);
  }

  // 5-2) 우편소인일이 원래 말일 이내면 청구기간을 지킨 것으로 본다. (접수일이 늦게 도달해도 같다)
  if (소인일 !== null && 소인일 <= 말일) {
    const 보는날 = 기한 ?? 말일;
    return 결과만들기(
      "충족",
      `우편소인일이 기한 이내라 접수일이 늦더라도 청구기간을 지킨 것으로 본다.${추정표시}`,
      [
        ...과정,
        ...입력과정,
        `청구일로 보는 날: ${요일붙이기(보는날)} (우편소인일이 아니라 기간 만료일, 국세기본법 제61조 제3항·제80조의2)`,
      ],
    );
  }

  // 여기부터는 접수일·우편소인일이 원래 말일을 넘었다. 휴일로 미뤄진 기한을 알아야 판단할 수 있다.
  if (기한 === null) {
    return 결과만들기(
      "확인 필요",
      `기간 말일(${말일})이 지났으나, 말일이 휴일이라 기한이 미뤄지는지 알 수 없어 판단할 수 없다.${추정표시}`,
      [...과정, ...입력과정],
    );
  }

  if (접수일 !== null && 접수일 <= 기한) {
    return 결과만들기("충족", `접수일이 (휴일로 미뤄진) 기한 이내라 청구기간을 지켰다.${추정표시}`, [...과정, ...입력과정]);
  }

  if (소인일 !== null) {
    if (소인일 <= 기한) {
      return 결과만들기(
        "충족",
        `우편소인일이 (휴일로 미뤄진) 기한 이내라 접수일이 늦더라도 청구기간을 지킨 것으로 본다.${추정표시}`,
        [
          ...과정,
          ...입력과정,
          `청구일로 보는 날: ${요일붙이기(기한)} (우편소인일이 아니라 기간 만료일, 국세기본법 제61조 제3항·제80조의2)`,
        ],
      );
    }
    return 결과만들기(
      "미충족",
      `우편소인일${접수일 ? "과 접수일이 모두" : "이"} 기한을 넘어 청구기간이 지났다.${추정표시}`,
      [...과정, ...입력과정],
    );
  }

  // 우편소인일이 없는데 접수일이 기한을 넘은 경우: 우편으로 냈는지 알 수 없다.
  return 결과만들기(
    "확인 필요",
    `접수일이 기한을 넘었으나 우편소인일이 없다. 우편으로 제출했다면 우편소인일에 따라 결과가 달라지므로 확인이 필요하다.${추정표시}`,
    [...과정, ...입력과정],
  );
}
