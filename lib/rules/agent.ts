// 대리인 부적격 점검
// Design Ref: §2-4 — 판정은 같은 입력이면 항상 같은 결과가 나오는 규칙 코드로 만든다. (AI를 쓰지 않는다)
// Plan SC: PLAN 작업 8번 — 사건 유형(소액 여부)과 대리인의 관계·자격을 대리인 자격 요건과 대조하고, 대조한 기준을 보여준다.
//
// 근거 (2026-11-20 www.law.go.kr에서 확인):
//  - 국세기본법 제59조 제1항: 심판청구인과 처분청은 변호사, 세무사 또는 세무사등록부·공인회계사 세무대리업무등록부에
//    등록한 공인회계사를 대리인으로 선임할 수 있다.
//  - 국세기본법 제59조 제2항: 청구 대상이 제78조 제1항 단서에 따른 소액인 경우에는 청구인의 배우자,
//    4촌 이내의 혈족 또는 그 배우자의 4촌 이내의 혈족도 대리인으로 선임할 수 있다.
//  - 국세기본법 제59조 제3항: 대리인의 권한은 서면으로 증명하여야 한다. (위임장 확인은 담당자가 한다)
//  - 국세기본법 시행령 제62조 제1호: 소액은 심판청구금액이 5천만원(지방세는 2천만원) 미만인 것으로서,
//    법령 해석에 관한 것이 아닌 것 등 추가 요건에 해당하는 것이다.
//
// 판정 기준 (이 파일이 정한 해석)
//  - 충족    : 대리인이 없다(해당 없음) / 대리인이 변호사·세무사(·등록 공인회계사) / 소액 사건에서 배우자·4촌 이내 혈족
//  - 미충족  : 일반 사건에서 가족이 대리 / 청구금액이 소액 기준 이상 / 관계가 없다고 명시되었거나 5촌 이상으로 적힌 경우
//  - 판단 필요: 관계·자격 글이 위 어디에도 분명히 맞지 않거나(인척, 법정대리인 등), 소액 여부가 서로 맞지 않는 경우
//  - 확인 필요: 대리인은 있는데 관계·자격 또는 가족 대리에 필요한 사건 유형·청구금액이 비어 있는 경우
//  - 관계·자격은 사람이 적은 글이라 키워드로만 읽는다. "없음·아님"이 들어 있으면 자격이 있다고 읽지 않는다.
//  - 소액 판정에는 법령 해석 여부 등 서류로만 알 수 없는 요건이 있어, 금액은 "필요 조건"으로만 쓰고
//    금액이 기준 미만인 일반 사건은 미충족으로 단정하지 않고 "판단 필요"로 둔다.
//  - 이 점검은 국세 기준(5천만원)만 쓴다. 지방세(2천만원)는 구분하지 않는다.
//
// 조문 원문을 보여주는 "조문 파일"은 PLAN 작업 16번에서 만든다. 그래서 미충족 결과에는 "조문확인필요"를 켠다.

import type { 사건정보, 점검결과 } from "../types";
import { 상태뜻 } from "../types";

export const 소액기준금액 = 50_000_000; // 원. 국세 기준, 시행령 제62조 제1호 (미만이 소액)

function 글자있음(값: string | null | undefined): 값 is string {
  return typeof 값 === "string" && 값.trim() !== "";
}

function 결과만들기(상태: 점검결과["상태"], 근거: string): 점검결과 {
  return {
    항목: "대리인부적격",
    상태,
    상태뜻: 상태뜻[상태],
    근거,
    ...(상태 === "미충족" ? { 조문확인필요: true } : {}),
  };
}

const 아님표현 = /없|아님|아니|무관/;
const 전문직 = /변호사|세무사|공인회계사/;
const 가족말 = [
  "배우자", "남편", "아내", "부모", "아버지", "어머니", "부친", "모친", "자녀", "아들", "딸",
  "형제", "자매", "형", "누나", "오빠", "언니", "동생", "조부", "조모", "할아버지", "할머니",
  "손자", "손녀", "삼촌", "외삼촌", "이모", "고모", "숙부", "조카", "시부모", "장인", "장모", "처남", "처제",
];
const 인척말 = /인척|사위|며느리|형수|제수|숙모|외숙모|법정대리/;

type 관계분류 =
  | { 종류: "전문직"; 설명: string }
  | { 종류: "가족"; 설명: string }
  | { 종류: "가족아님"; 설명: string }
  | { 종류: "모호"; 설명: string };

function 관계읽기(글: string): 관계분류 {
  const 문장 = 글.trim();
  const 부정 = 아님표현.test(문장);

  // 촌수가 적혀 있으면 4촌 이내인지 본다. (예: "3촌 이내 혈족", "5촌")
  const 촌수 = 문장.match(/(\d+)\s*촌/);
  const 인척 = 인척말.test(문장);

  if (!부정 && 전문직.test(문장)) {
    const 회계사만 = /공인회계사/.test(문장) && !/변호사|세무사/.test(문장.replace(/공인회계사/g, ""));
    if (회계사만 && !/등록/.test(문장)) {
      return { 종류: "모호", 설명: "공인회계사는 세무대리업무등록부에 등록한 경우만 대리인이 될 수 있는데 등록 여부가 적혀 있지 않다" };
    }
    return { 종류: "전문직", 설명: "변호사·세무사(등록 공인회계사)" };
  }
  if (부정 && /관계/.test(문장)) {
    return { 종류: "가족아님", 설명: "청구인과 관계가 없다고 적혀 있다" };
  }
  if (인척) {
    return { 종류: "모호", 설명: "인척 또는 법정대리 관계로 적혀 있어 배우자·4촌 이내 혈족에 해당하는지 분명하지 않다" };
  }
  if (!부정 && 촌수) {
    return Number(촌수[1]) <= 4
      ? { 종류: "가족", 설명: `${촌수[1]}촌 이내 혈족` }
      : { 종류: "가족아님", 설명: `${촌수[1]}촌으로 4촌 이내 혈족이 아니다` };
  }
  if (!부정 && 가족말.some((말) => 문장.includes(말))) {
    return { 종류: "가족", 설명: "배우자 또는 4촌 이내 혈족" };
  }
  return { 종류: "모호", 설명: "적힌 관계·자격이 대리인 자격 요건 어디에 해당하는지 분명하지 않다" };
}

const 기준안내 =
  "대조한 기준: 국세기본법 제59조 제1항(변호사·세무사·등록 공인회계사), 제2항(소액 사건에 한해 배우자·4촌 이내 혈족). " +
  "소액은 시행령 제62조 제1호에 따라 청구금액 5천만원 미만 등. 대리권은 서면(위임장)으로 증명해야 하므로(제59조 제3항) 담당자가 확인한다.";

export function 대리인부적격점검(정보: 사건정보): 점검결과 {
  if (!글자있음(정보.대리인)) {
    return 결과만들기("충족", `선임된 대리인이 없어 대리인 자격을 따질 대상이 아니다. (청구인 본인이 청구) ${기준안내}`);
  }
  if (!글자있음(정보.대리인관계자격)) {
    return 결과만들기(
      "확인 필요",
      `대리인(${정보.대리인.trim()})이 있으나 청구인과의 관계·자격이 입력되지 않아 대조할 수 없다. 서류에서 확인해야 한다. ${기준안내}`,
    );
  }

  const 대리인 = 정보.대리인.trim();
  const 글 = 정보.대리인관계자격.trim();
  const 관계 = 관계읽기(글);

  if (관계.종류 === "전문직") {
    return 결과만들기("충족", `대리인(${대리인})의 자격이 "${글}"로 ${관계.설명}에 해당한다. ${기준안내}`);
  }
  if (관계.종류 === "모호") {
    return 결과만들기("판단 필요", `대리인(${대리인})의 관계·자격 "${글}": ${관계.설명}. 담당자가 판단해야 한다. ${기준안내}`);
  }

  // 여기부터는 가족 관계(또는 가족이 아님)라서 소액 여부가 중요하다.
  const 금액 = typeof 정보.청구금액 === "number" ? 정보.청구금액 : null;
  const 금액소액 = 금액 === null ? null : 금액 < 소액기준금액;

  if (관계.종류 === "가족아님") {
    return 결과만들기(
      "미충족",
      `대리인(${대리인})의 관계·자격 "${글}": ${관계.설명}. 변호사·세무사 등 자격도 확인되지 않아 대리인이 될 수 없다. ${기준안내}`,
    );
  }

  // 관계.종류 === "가족"
  if (!정보.사건유형) {
    return 결과만들기(
      "확인 필요",
      `대리인(${대리인})은 ${관계.설명}으로 적혀 있다. 가족 대리는 소액 사건에서만 가능한데 사건 유형이 입력되지 않아 판단할 수 없다. ${기준안내}`,
    );
  }
  if (정보.사건유형 === "소액") {
    if (금액소액 === null) {
      return 결과만들기(
        "확인 필요",
        `대리인(${대리인})은 ${관계.설명}이고 사건 유형이 소액이나, 청구금액이 입력되지 않아 소액 기준(5천만원 미만)을 확인할 수 없다. ${기준안내}`,
      );
    }
    if (!금액소액) {
      return 결과만들기(
        "판단 필요",
        `사건 유형은 소액이나 청구금액 ${금액!.toLocaleString("ko-KR")}원이 소액 기준(5천만원 미만) 이상이라 서로 맞지 않는다. 소액 여부를 담당자가 확인해야 한다. ${기준안내}`,
      );
    }
    return 결과만들기(
      "충족",
      `대리인(${대리인})은 ${관계.설명}이고, 소액 사건(청구금액 ${금액!.toLocaleString("ko-KR")}원)이라 대리인이 될 수 있다. ${기준안내}`,
    );
  }

  // 일반 사건
  if (금액소액 === true) {
    return 결과만들기(
      "판단 필요",
      `대리인(${대리인})은 ${관계.설명}이고 사건 유형은 일반이나, 청구금액 ${금액!.toLocaleString("ko-KR")}원은 소액 기준(5천만원 미만) 안이다. 법령 해석 여부 등 나머지 소액 요건에 따라 달라지므로 담당자가 판단해야 한다. ${기준안내}`,
    );
  }
  return 결과만들기(
    "미충족",
    `대리인(${대리인})은 ${관계.설명}이나, 일반 사건에서는 변호사·세무사 등만 대리인이 될 수 있다. ${기준안내}`,
  );
}
