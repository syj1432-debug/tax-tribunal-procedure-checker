// 점검 결과에 "서류상 위치" 붙이기
// Design Ref: §1-3 — 결과마다 서류상 위치(파일·쪽)를 보여준다. (PRD 5번: 미충족에는 반드시)
// Plan SC: PLAN 성공 기준 2번 — 근거 조문과 서류상 근거 위치가 함께 보인다. (CHECK.md G1)
//
// 점검에 쓴 값마다 어디서 읽었는지를 정리한다.
//  - 가상 서류에서 AI가 읽은 값: "청구서.pdf 1쪽"처럼 출처를 적는다.
//  - 담당자가 직접 입력하거나 고친 값: 프로그램이 서류 위치를 알 수 없으므로 "직접 입력"이라고 밝히고, 담당자가 확인하게 한다.
//  - 값이 비어 있는 칸은 적지 않는다. (찾을 위치가 없다)
// 파일 이름에 개인정보가 들어 있을 수 있어 마스킹을 거친다.

import { 마스킹 } from "./mask";
import type { 값이름, 사건정보, 점검결과, 점검항목 } from "./types";

const 칸이름표: Partial<Record<값이름, string>> = {
  처분을안날: "처분을 안 날",
  처분일: "처분일",
  접수일: "접수일",
  우편소인일: "우편소인일",
  처분서있음: "처분서",
  처분청: "처분청",
  청구인: "청구인",
  처분상대방: "처분 상대방",
  대리인: "대리인",
  대리인관계자격: "대리인과의 관계·자격",
  사건유형: "사건 유형",
  청구금액: "청구금액",
};

// 항목마다 판정에 쓴 값
const 쓴값: Record<점검항목, 값이름[]> = {
  청구기간: ["처분을안날", "처분일", "접수일", "우편소인일"],
  처분부존재: ["처분서있음", "처분일", "처분청"],
  청구인부적격: ["청구인", "처분상대방"],
  대리인부적격: ["대리인", "대리인관계자격", "사건유형", "청구금액"],
};

function 비어있음(값: unknown): boolean {
  return 값 === null || 값 === undefined || 값 === "";
}

/** 항목에서 쓴 값들의 서류상 위치를 줄바꿈으로 이은 글. 적을 것이 없으면 undefined. */
export function 서류상위치글(정보: 사건정보, 항목: 점검항목): string | undefined {
  const 줄들: string[] = [];
  for (const 이름 of 쓴값[항목]) {
    if (비어있음(정보[이름])) continue;
    const 출처 = 정보.출처?.[이름];
    const 직접고침 = 정보.사용자수정?.includes(이름);
    const 위치 =
      출처 && !직접고침
        ? `${마스킹(출처.파일명)}${출처.쪽수 ? ` ${출처.쪽수}쪽` : ""}`
        : "직접 입력한 값 (서류상 위치는 담당자가 확인)";
    줄들.push(`${칸이름표[이름]}: ${위치}`);
  }
  return 줄들.length > 0 ? 줄들.join("\n") : undefined;
}

/** 결과에 서류상 위치를 붙여 새 결과로 돌려준다. */
export function 서류상위치붙이기(결과: 점검결과, 정보: 사건정보): 점검결과 {
  const 위치 = 서류상위치글(정보, 결과.항목);
  return 위치 ? { ...결과, 서류상위치: 위치 } : 결과;
}
