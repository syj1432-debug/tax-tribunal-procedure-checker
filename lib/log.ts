// 서류 내용을 남기지 않는 로그
// Design Ref: §4 — 서버 코드에서 서류 내용을 로그에 출력하지 않는다. (파일 이름·크기도 남기지 않는 것이 기본)
// Plan SC: PLAN 작업 10번 — 서류 내용이 로그에 남지 않는다.
//
// 이 프로젝트에서 로그는 이 파일의 함수로만 남긴다. console.log 등을 직접 쓰지 않는다.
// (tests/log.test.ts가 다른 파일에서 console을 쓰면 시험에서 잡는다.)
// 로그에는 "어떤 일이 일어났는지"를 나타내는 미리 정해 둔 이름만 쓸 수 있고,
// 서류 내용·이름·번호·파일 이름 같은 값은 넣을 자리 자체가 없다.

export type 로그이벤트 =
  | "점검실행"
  | "점검종료"
  | "업로드받음"
  | "추출성공"
  | "추출실패"
  | "크기초과";

export function 기록(이벤트: 로그이벤트): void {
  // 이름 외에는 아무것도 남기지 않는다.
  console.info(`[점검기] ${이벤트}`);
}
